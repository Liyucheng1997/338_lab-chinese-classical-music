// 《渔舟唱晚》——古筝独奏（娄树华改编，曹正订谱；1=D，慢板 ♩=58 → 快板渐快 → 还原）
//
// 结构：
//   一、如歌的慢板（老八板变奏）：八度低音 + 高音旋律，装饰音按音；
//   二、慢板下半：四音上行小走句 + 摇指对音，逐段模进下行，渐慢；
//   三、快板：♩=72 → 84 → 100+，摇指对音 + 五连音花指（下行）模进，渐快渐强，层层推向高潮；
//   四、还原速度，刮奏收束，渐慢，结尾。
//
// 记谱说明见 src/score/jianpu.js 顶部；本文件按原谱逐小节整理为文字简谱，
// 每小节的拍数由解析器校验（npm test 会报告不符的小节）。
//   [a b]  和弦（同时拨）   <a b c>_  走句（在给定总时值内等分）   ~ 摇指   ^ 按音上滑

/** 快板小节：摇指对音（低八度+本音）+ 本音引导 + 五连音下行花指。 */
function fb(p1, p2, lead, run, leadFlags = '') {
  return `${p1}_ ${p2}_~ ${lead}_${leadFlags}~ <${run}>_ |`;
}
/** 快板后段小节：和弦（两个音同时拨）+ 四音走句。 */
function fd(p1, p2, dyad, run) {
  return `${p1}_ ${p2}_~ [${dyad}]_^ <${run}>_ |`;
}
/** 慢板下半：四音上行小走句 + 摇指对音（2/4）。 */
function fig(a, b, c, d, pl, ph) {
  return `${a}__. ${b}___ ${c}__ ${d}__ ${pl}_ ${ph}_~ |`;
}

